import type { PetKind, PetStage } from "./pet-state";

export const SPRITE_SIZE = 18;

function sprite(lines: string[]): string[] {
  const clipped = lines.slice(0, SPRITE_SIZE);
  const verticalGap = SPRITE_SIZE - clipped.length;
  const top = Math.floor(verticalGap / 2);
  const bottom = verticalGap - top;
  const transparentRow = ".".repeat(SPRITE_SIZE);

  return [
    ...Array.from({ length: top }, () => transparentRow),
    ...clipped.map((line) => {
      if (!/^[.12345]+$/.test(line) || line.length > SPRITE_SIZE) {
        throw new Error(`Invalid pixel row: ${line}`);
      }
      const horizontalGap = SPRITE_SIZE - line.length;
      const left = Math.floor(horizontalGap / 2);
      return `${".".repeat(left)}${line}${".".repeat(horizontalGap - left)}`;
    }),
    ...Array.from({ length: bottom }, () => transparentRow),
  ];
}

